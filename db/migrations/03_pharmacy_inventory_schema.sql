-- ============================================================================
-- Migration : 03_pharmacy_inventory_schema.sql
-- Purpose   : Multi-store pharmacy inventory schema (ported from the legacy
--             VFP6.0 systems BASEMENT + Satell under E:\Projects\HMC\PHARSYS).
--
-- WHY THIS SHAPE
--   The legacy system kept ONE COPY OF EVERYTHING PER STORE. Each store folder
--   carried its own INVMAST.DBF holding the same drug plus that store's own
--   prices, ONHAND, OP_BAL, OP_TRADE and OP_RETAIL:
--       BASEMENT\CURRENT\INVMAST.DBF  4,449 rows x 22 fields  (main store)
--       Satell\CURRENT\invmast.dbf    4,929 rows x 24 fields  (sub store)
--   Satell's copy is a superset of Basement's (the extra two fields are
--   ACTIVE and TOP). Reproducing that shape in SQL Server would duplicate the
--   drug master once per store and drift.
--
--   So the master is stored ONCE, and everything that genuinely varies per
--   store is lifted into PHITEMSTOCK keyed by (ItemId, StoreId). That is the
--   "handle with a flag instead of a second table" rule from the brief, done
--   as a child row rather than a discriminator column.
--
--   Transactions are stored the same way: the legacy store-issue was not a
--   table of its own, it was a PUR_MAST/PUR_DET receipt written into the
--   RECEIVING store's file and tagged with the source (all 65 Satell receipts
--   carry SPCODE='BASE', INVC='Basement', POST='Y'). Here that becomes one
--   PHPURCHASE table with StoreId (receiving) and SourceStoreId (issuing), so
--   a main-store issue and a supplier purchase are the same row shape.
--
--   PHSTOCKMOVEMENT is the single ledger every on-hand / open-balance /
--   ending-inventory figure is derived from, rather than a mutable ONHAND
--   column copied per store.
--
-- DATA NOTE
--   BASEMENT's own purchase history is absent from the supplied copy
--   (BASEMENT\CURRENT holds only INVMAST.DBF). The main store therefore opens
--   from its INVMAST OP_BAL / OP_TRADE / ONHAND figures as a single OPENING
--   movement, and all movement from go-live forward. See
--   workspace\logs\pharmacy-migration.md.
--
-- ADDITIVE-ONLY RULE: no pre-existing table or column is altered or dropped.
--
-- Developer : Tajwer Jalal
-- Date      : 19-Oct-2026
-- Time      : 10:55
-- ============================================================================
SET NOCOUNT ON;
