using System;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace HmisWeb.Models.Recovery
{
    /// <summary>
    /// RECOVERY INV - company invoice/letter header (one row per letter raised on
    /// a company).Ports VFP BillSys form INVOICE (bs0601) onto a single canonical
    /// table pair - DocType discriminates IPD ('I', this screen) from OPD ('O',
    /// later screen) so the review finding R-02 (receipts keyed per patient with
    /// no invoice link) can be closed by future allocation rows pointing at
    /// InvoiceId rather than at a regno alone.
    ///
    /// Business rules
    ///   * DocNo is generated by RecoveryInvoiceService (CID/MMYYYY, '-n' suffix
    ///     when the company/month-year slot was already used) - numbering is
    ///     owned by the app, never hand-typed (review finding R-01).
    ///   * Status 'O' = open (editable), 'C' = cancelled (read-only, badge).
    ///   * TotAmt is only ever the sum of the RECOVERY_INVDET lines of the
    ///     header; a header with no lines must not exist (review finding G-01).
    ///   * Rows are never physically deleted - Cancel reasons go to
    ///     RECOVERY_AUDIT alongside before/after values.
    ///
    /// Developer: Tajwer Jalal | Date: 20-Oct-2026 | Time: 18:30
    /// </summary>
    [Table("RECOVERY_INV")]
    public class RecoveryInvoice
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        /// <summary>Generated document number, e.g. A003/072026 or A003/072026-2.</summary>
        [MaxLength(20)]
        public string DocNo { get; set; }

        /// <summary>'I' IPD / 'O' OPD - one table pair covers both flows.</summary>
        [MaxLength(1)]
        public string DocType { get; set; }

        /// <summary>COMPANY.ID of the billed company.</summary>
        [MaxLength(8)]
        public string CompanyCode { get; set; }

        public DateTime InvoiceDate { get; set; }

        /// <summary>Date the bills were submitted to the company (letter date).</summary>
        public DateTime? SubmissionDate { get; set; }

        public int? BillMonth { get; set; }

        public int? BillYear { get; set; }

        [MaxLength(200)]
        public string Remarks { get; set; }

        /// <summary>Sum of the lines; recomputed on every line change.</summary>
        public decimal TotAmt { get; set; }

        /// <summary>'O' open / 'C' cancelled.</summary>
        [MaxLength(1)]
        public string Status { get; set; }

        [MaxLength(40)]
        public string CreatedBy { get; set; }

        public DateTime CreatedAt { get; set; }

        [MaxLength(40)]
        public string EditedBy { get; set; }

        public DateTime? EditedAt { get; set; }

        [Timestamp]
        public byte[] RowVer { get; set; }
    }

    /// <summary>
    /// RECOVERY INVDET - one billed-patient line of an invoice.Amount defaults
    /// from REGISTER.TBILLAMT exactly like the VFP child grid did (bs0601 lookup
    /// of company-billed inpatients).Unique per (invoice, regno): a patient
    /// appears once per letter, and the duplicate-patient-across-open-invoices
    /// guard is enforced in the service.
    ///
    /// Developer: Tajwer Jalal | Date: 20-Oct-2026 | Time: 18:30
    /// </summary>
    [Table("RECOVERY_INVDET")]
    public class RecoveryInvoiceDet
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        /// <summary>
        /// FK to the header (RECOVERY_INV.Id). Kept as a real navigation so EF
        /// cascades the header's minted identity into the lines inside one
        /// save; a bare FK would push 0 and trip the FK constraint.
        /// Change Log 20-Oct-2026 20:35 (Tajwer Jalal): navigation added after
        /// the e2e test reproduced FK_RECOVERY_INVDET_Inv conflicts.
        /// </summary>
        public long InvoiceId { get; set; }

        public RecoveryInvoice Invoice { get; set; }

        /// <summary>REGISTER.REGNO (TYPE='I', BILLGEN=1 at entry time).</summary>
        [MaxLength(16)]
        public string RegNo { get; set; }

        public decimal BillAmt { get; set; }

        [MaxLength(100)]
        public string Remarks { get; set; }

        [MaxLength(40)]
        public string CreatedBy { get; set; }

        public DateTime? CreatedAt { get; set; }
    }

    /// <summary>
    /// RECOVERY AUDIT - immutable before/after log for every Recovery write
    /// (pattern of IpdBillAudit/OPDBILL_AUDIT).This closes review finding R-03 /
    /// R-18 for the migrated screens: obilvalue-style silent edits get a reason
    /// and a trail from the day they are rebuilt here.
    ///
    /// Developer: Tajwer Jalal | Date: 20-Oct-2026 | Time: 18:30
    /// </summary>
    [Table("RECOVERY_AUDIT")]
    public class RecoveryAudit
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        /// <summary>CREATE / EDIT / CANCEL (future: RECEIPT, ALLOC, BILLCORR).</summary>
        [MaxLength(20)]
        public string Action { get; set; }

        [MaxLength(20)]
        public string Entity { get; set; }

        [MaxLength(80)]
        public string EntityKey { get; set; }

        [MaxLength(40)]
        public string Field { get; set; }

        [MaxLength(200)]
        public string OldValue { get; set; }

        [MaxLength(200)]
        public string NewValue { get; set; }

        [MaxLength(300)]
        public string Reason { get; set; }

        public long? InvoiceId { get; set; }

        public long? WebUserId { get; set; }

        [MaxLength(80)]
        public string UserName { get; set; }

        [MaxLength(64)]
        public string RoleName { get; set; }

        /// <summary>UTC stamp of the audit row.</summary>
        public DateTime CreatedAt { get; set; }
    }

    /// <summary>
    /// RECOVERY RCPT - receipt/cheque header (one row per money received).
    /// Ports VFP BillSys form RECPT (bs0603, rcpt/rcptf); the OPD screen
    /// (orecpt) reuses this same pair later - no duplicate tables.
    ///
    /// Business rules
    ///   * ReceiptNo minted by RecoveryReceiptService, serial
    ///     RCP/MM/YYYY-nnnn (UNIQUE); legacy VNO was zero-padded and NOT
    ///     numbered by the form (review R-01).
    ///   * Method 'C' cash (auto-cleared) / 'Q' cheque - replaces the legacy
    ///     "blank CHQNO means cash" convention and adds the cheque STATUS the
    ///     legacy system never had: 'P' pending -> 'C' cleared / 'B' bounced.
    ///   * TotAmt = sum of the allocation lines' RcptAmt only (the bankable
    ///     money - legacy TOT_AMT semantic, verified 13,856/13,859 in review).
    ///   * Rows are never physically deleted - Cancel (mandatory reason).
    ///
    /// Developer: Tajwer Jalal | Date: 21-Oct-2026 | Time: 10:45
    /// </summary>
    [Table("RECOVERY_RCPT")]
    public class RecoveryRcpt
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        [MaxLength(20)]
        public string ReceiptNo { get; set; }

        [MaxLength(1)]
        public string Method { get; set; }

        public DateTime RcptDate { get; set; }

        [MaxLength(8)]
        public string CompanyCode { get; set; }

        [MaxLength(32)]
        public string ChequeNo { get; set; }

        [MaxLength(80)]
        public string Bank { get; set; }

        public DateTime? ChequeDate { get; set; }

        [MaxLength(40)]
        public string RcvdBy { get; set; }

        /// <summary>Sum of allocation lines' RcptAmt (bankable money).</summary>
        public decimal TotAmt { get; set; }

        /// <summary>'P' pending / 'C' cleared /'B' bounced /'X' cancelled.</summary>
        [MaxLength(1)]
        public string Status { get; set; }

        [MaxLength(200)]
        public string Remarks { get; set; }

        [MaxLength(40)]
        public string CreatedBy { get; set; }

        public DateTime CreatedAt { get; set; }

        [MaxLength(40)]
        public string EditedBy { get; set; }

        public DateTime? EditedAt { get; set; }

        [Timestamp]
        public byte[] RowVer { get; set; }
    }

    /// <summary>
    /// RECOVERY RCPT ALLOC - one applied-money line of a receipt (legacy
    /// RCPTDET).Credit applied to the invoice = RcptAmt + ItaxDed + OthDed
    /// (legacy gross semantics); RcptAmt alone is what reaches the bank.
    /// InvoiceId NULL keeps the "received but never invoiced" advance money
    /// (legacy G-02 / 33,478 rows) which balances on the company ledger.
    ///
    /// Business rules
    ///   * UNIQUE per (receipt, patient) - the legacy one-line-per-regno-per-
    ///     voucher invariant, which holds in the data.
    ///   * Over-allocation is refused both per allocation line (vs
    ///     RECOVERY_INVDET.BillAmt - the G-04'885 rows' case) and per invoice
    ///     (vs RECOVERY_INV.TotAmt).
    ///
    /// Developer: Tajwer Jalal | Date: 21-Oct-2026 | Time: 10:45
    /// </summary>
    [Table("RECOVERY_RCPT_ALLOC")]
    public class RecoveryRcptAlloc
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        public long ReceiptId { get; set; }

        /// <summary>NULL = money received but never invoiced (advance book).</summary>
        public long? InvoiceId { get; set; }

        [MaxLength(16)]
        public string RegNo { get; set; }

        public decimal RcptAmt { get; set; }

        public decimal ItaxDed { get; set; }

        public decimal OthDed { get; set; }

        [MaxLength(50)]
        public string Remarks { get; set; }

        [MaxLength(40)]
        public string CreatedBy { get; set; }

        public DateTime? CreatedAt { get; set; }

        /// <summary>Header navigation - lets EF cascade ReceiptId on insert.</summary>
        public RecoveryRcpt Receipt { get; set; }
    }
}
